#!/usr/bin/env python3
"""Merge papers/group*.json into js/papers.js and check for problems.

Usage: python3 tools/build_papers.py
Fails (exit 1) if a type is missing, a list doesn't have 3 papers, a field is missing,
or the same arXiv paper appears under two types.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TYPES = [a + b + c + d for a in "EI" for b in "SN" for c in "TF" for d in "JP"]
FIELDS = ["title", "authors", "year", "venue", "arxiv", "project", "why_ko", "why_en"]

merged, errors = {}, []
for f in sorted((ROOT / "papers").glob("group*.json")):
    for t, v in json.loads(f.read_text()).items():
        if t in merged:
            errors.append(f"{t} defined twice ({f.name})")
        merged[t] = v

seen = {}
for t in TYPES:
    if t not in merged:
        errors.append(f"missing type {t}")
        continue
    for kind in ("foundational", "recent"):
        lst = merged[t].get(kind, [])
        if len(lst) != 3:
            errors.append(f"{t}.{kind} has {len(lst)} papers")
        for p in lst:
            for k in FIELDS:
                if k not in p:
                    errors.append(f"{t}.{kind} '{p.get('title')}' missing {k}")
            m = re.search(r"(\d{4}\.\d{4,5})", p.get("arxiv") or "")
            key = m.group(1) if m else p.get("title", "").lower()
            if key in seen:
                errors.append(f"duplicate: '{p.get('title')}' in {seen[key]} and {t}.{kind}")
            seen[key] = f"{t}.{kind}"
            if kind == "recent" and int(p.get("year", 0)) < 2025:
                errors.append(f"{t}.recent '{p['title']}' is from {p['year']}")

if errors:
    print("\n".join(errors))
    sys.exit(1)

out = ROOT / "js" / "papers.js"
out.write_text(
    "// Generated by tools/build_papers.py from papers/*.json — do not edit by hand.\n"
    "export const PAPERS = " + json.dumps({t: merged[t] for t in TYPES}, ensure_ascii=False, indent=1) + ";\n"
)
print(f"wrote {out} ({sum(len(merged[t][k]) for t in TYPES for k in ('foundational', 'recent'))} papers)")
