#!/usr/bin/env python3
"""Merge papers/group*.json into js/papers.js and check for problems.

Usage: python3 tools/build_papers.py
Fails (exit 1) if a type is missing, a list doesn't have 2 papers / 2 industry items,
a field is missing, or the same arXiv paper or product appears under two types.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TYPES = [a + b + c + d for a in "EI" for b in "SN" for c in "TF" for d in "JP"]
FIELDS = ["title", "authors", "year", "venue", "arxiv", "project", "why_ko", "why_en"]
IND_FIELDS = ["name", "org", "kind", "year", "url", "why_ko", "why_en"]
KINDS = {"startup", "bigtech", "company"}

merged, errors = {}, []
for f in sorted((ROOT / "papers").glob("group*.json")):
    for t, v in json.loads(f.read_text()).items():
        if t in merged:
            errors.append(f"{t} defined twice ({f.name})")
        merged[t] = v

seen = {}
for t in TYPES:
    if t not in merged:
        errors.append(f"missing type {t}")
        continue
    for kind in ("foundational", "recent"):
        lst = merged[t].get(kind, [])
        if len(lst) != 2:
            errors.append(f"{t}.{kind} has {len(lst)} papers")
        for p in lst:
            for k in FIELDS:
                if k not in p:
                    errors.append(f"{t}.{kind} '{p.get('title')}' missing {k}")
            m = re.search(r"(\d{4}\.\d{4,5})", p.get("arxiv") or "")
            key = m.group(1) if m else p.get("title", "").lower()
            if key in seen:
                errors.append(f"duplicate: '{p.get('title')}' in {seen[key]} and {t}.{kind}")
            seen[key] = f"{t}.{kind}"
            if kind == "recent" and int(p.get("year", 0)) < 2025:
                errors.append(f"{t}.recent '{p['title']}' is from {p['year']}")
    ind = merged[t].get("industry", [])
    if len(ind) != 2:
        errors.append(f"{t}.industry has {len(ind)} items")
    for p in ind:
        for k in IND_FIELDS:
            if k not in p:
                errors.append(f"{t}.industry '{p.get('name')}' missing {k}")
        if p.get("kind") not in KINDS:
            errors.append(f"{t}.industry '{p.get('name')}' has kind {p.get('kind')!r}")
        key = (p.get("url") or "").rstrip("/")
        if key in seen:
            errors.append(f"duplicate: '{p.get('name')}' in {seen[key]} and {t}.industry")
        seen[key] = f"{t}.industry"

if errors:
    print("\n".join(errors))
    sys.exit(1)

out = ROOT / "js" / "papers.js"
out.write_text(
    "// Generated by tools/build_papers.py from papers/*.json — do not edit by hand.\n"
    "export const PAPERS = " + json.dumps({t: merged[t] for t in TYPES}, ensure_ascii=False, indent=1) + ";\n"
)
n_pap = sum(len(merged[t][k]) for t in TYPES for k in ("foundational", "recent"))
n_ind = sum(len(merged[t]["industry"]) for t in TYPES)
print(f"wrote {out} ({n_pap} papers, {n_ind} industry items)")
